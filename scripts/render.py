def ref_ranges(refs):
    """Propositions of one book in order, as our prose writes them: consecutive runs
    joined by an en dash (STYLE §5). ["I.1", …, "I.28", "I.31"] ↦ "I.1–I.28 and I.31"."""
    runs = []
    for r in refs:
        b, num = r.split(".")
        if runs and runs[-1][0] == b and runs[-1][2] == int(num) - 1:
            runs[-1][2] = int(num)
        else:
            runs.append([b, int(num), int(num)])
    return and_list([f"{b}.{lo}" if lo == hi else f"{b}.{lo}–{b}.{hi}" for b, lo, hi in runs])


def postulate5_sentence(book, facts, proved):
    """Where the parallel postulate comes into the book's proofs, from facts.json, in
    the certificate's words: what a proof uses, never what a proposition needs."""
    count = BOOKS[book][0]
    without = [r for r in proved if "Postulate5" not in facts[r]["axioms"]]
    using = [r for r in proved if r not in without]
    direct = [r for r in using if "Postulate5" in facts[r]["direct_axioms"]]
    # Where Heath's brackets first give Post. 5 in this book.
    heath_first = next((f"{book}.{n}" for n in range(1, count + 1)
                        if "Post. 5" in heath.justifications(sum(split_porism(book, n), []))),
                       None)
    if not using:
        return "None of the proofs uses the parallel postulate."
    if not without:
        if direct:
            where = ", where Euclid calls on it," if direct[0] == heath_first else ""
            rest = "the others through" if len(direct) == 1 else "the rest through"
            return (f"Every proof uses the parallel postulate: {and_list(direct)}'s directly"
                    f"{where} and {rest} the propositions they cite.")
        return "Every proof uses the parallel postulate, through the propositions it cites."
    first = using[0]
    just = ", just where Euclid first calls on it" if first == heath_first else ""
    return (f"Our proofs of {len(without)} propositions do not use the parallel postulate: "
            f"{ref_ranges(without)}. The first proof that does is {first}'s{just}.")


def overlap_sentences(overlap, facts, records, links, up):
    """What a book's summary says of the propositions an axiom already contains, or
    supplies a step of a proof of, told apart by the record's [overlap] `kind` and by
    whether the proof rests on all, some or none of those axioms (facts.json's `axioms`):
    "In I.23 one of our tacit rules supplies a step of a proof of the proposition, and our
    proof rests on it"; "In I.2 and I.3 our tacit rules supply a step of a proof of each
    proposition, but our proofs never use those rules." Only a rule that states the
    proposition or gives it at once is said to contain it, as in the overlap catalogue.
    Where an overlap names several rules together, it says so, but not of rules that
    contain the proposition and go unused; partial use names the rules used and unused
    separately for each proposition. A proposition that several combinations of rules
    contain (`ways`) has a sentence of its own, naming each combination and which of its
    rules our proof rests on, in the same place as a partial use."""
    def rules(r):
        return overlap_rules(records[r]["overlap"])

    def several(r):
        return len(overlap_ways(records[r]["overlap"])) > 1

    def together(rs):
        multi = [f"{r}, {number_word(len(rules(r)))} of them together" for r in rs
                 if len(rules(r)) > 1]
        return f" ({'; '.join('in ' + m for m in multi)})" if multi else ""

    single = [r for r in overlap if not several(r)]
    family = ("tacit rules" if all(x.startswith("Tacit.") for r in single for x in rules(r))
              else "axioms")
    contain = [r for r in single if not overlap_steps(records[r]["overlap"])]
    step = [r for r in single if r not in contain]
    used_rules = {r: overlap_rests(facts.get(r), records[r]["overlap"]) for r in single}
    rests = [r for r in single if used_rules[r] == rules(r)]
    partial = [r for r in single if used_rules[r] and r not in rests]
    out = []
    used = [r for r in contain if r in rests]
    if used:
        extra = together(used)
        if len(used) == 1 and not extra:
            out.append(f"In {links(used)} one of our {family} already contains the proposition, "
                       "and our proof rests on it, so the proof retraces Euclid's argument "
                       "within our rules and does not establish the rule.")
        else:
            out.append(f"In {and_list(links([r]) for r in used)} our {family} already contain "
                       f"the proposition{extra}, and our proofs rest on them, so each retraces "
                       "Euclid's argument within our rules and does not establish them.")
    unused = [r for r in contain if not used_rules[r]]
    if unused:
        if len(unused) == 1:
            out.append(f"In {links(unused)} one of our {family} contains the proposition too, "
                       "but our proof never uses that rule.")
        else:
            out.append(f"In {and_list(links([r]) for r in unused)} our {family} contain the "
                       "propositions too, but our proofs never use those rules.")
    used = [r for r in step if r in rests]
    if used:
        extra = together(used)
        if len(used) == 1 and not extra:
            out.append(f"In {links(used)} one of our {family} supplies a step of a proof of "
                       "the proposition, and our proof rests on it.")
        else:
            out.append(f"In {and_list(links([r]) for r in used)} our {family} supply a step of "
                       f"a proof of each proposition{extra}, and our proofs rest on them.")
    unused = [r for r in step if not used_rules[r]]
    if unused:
        extra = together(unused)
        if len(unused) == 1 and not extra:
            out.append(f"In {links(unused)} one of our {family} supplies a step of a proof "
                       "of the proposition, but our proof never uses that rule.")
        else:
            out.append(f"In {and_list(links([r]) for r in unused)} our {family} supply a step "
                       f"of a proof of each proposition{extra}, but our proofs never use those "
                       "rules.")
    for r in (r for r in overlap if r in partial or several(r)):
        ov = records[r]["overlap"]
        if several(r):
            contains = overlap_contains_ways(facts.get(r), ov, "the proposition")
            out.append(f"In {links([r])} {contains}.")
            continue
        claim = ("supply a step of a proof of the proposition" if overlap_steps(ov)
                 else "already contain the proposition")
        out.append(f"In {links([r])} {overlap_word(ov)} {claim}; "
                   f"{overlap_use(facts.get(r), ov)}.")
    out.append(f"[The overlap catalogue]({up}docs/reports/overlaps.md) gives each.")
    return " ".join(out)


def book_summary(book, facts, records, href, postulate5=True, up=""):
    """A book's completion summary, one line of Markdown generated from facts.json and
    the review records: how many propositions are proved, how many statements are
    whole, restricted or in part, whose argument the proofs follow, the propositions an
    axiom already contains or supplies a step of a proof of, and (unless `postulate5` is
    False) where the parallel postulate comes in. `href(ref)` is the link to a
    proposition's page. The same line heads the book's index, its section of
    CERTIFICATE.md and its row of README.md."""
    count = BOOKS[book][0]
    refs = [f"{book}.{n}" for n in range(1, count + 1)]

    def links(rs):
        return ", ".join(f"[{r}]({href(r)})" for r in rs)

    proved = [r for r in refs if facts.get(r, {}).get("status") == "proved"]
    head = (f"**All {count} propositions proved in Lean**" if len(proved) == count else
            f"**{len(proved)} of {count} propositions proved in Lean**")
    reviewed = [r for r in proved if records.get(r)]
    scope = {s: [r for r in reviewed if records[r]["statement"]["scope"] == s]
             for s in ("full", "restricted", "partial")}
    def states(k):
        return f"{k} as Euclid states {'it' if k == 1 else 'them'}"

    out = []
    if not reviewed:
        out.append(head + ".")
    elif not scope["restricted"] and not scope["partial"]:
        out.append(head + (", every one as Euclid states it." if len(reviewed) == len(proved)
                           else f": {states(len(scope['full']))}."))
    else:
        parts = [states(len(scope["full"]))] if scope["full"] else []
        if scope["restricted"]:
            parts.append(f"{len(scope['restricted'])} for a restricted statement "
                         f"({links(scope['restricted'])})")
        if scope["partial"]:
            parts.append(f"{len(scope['partial'])} in part, leaving clauses to Euclid's words "
                         f"({links(scope['partial'])})")
        out.append(f"{head}: {and_list(parts)}.")
    unreviewed = [r for r in proved if not records.get(r)]
    if unreviewed:
        out.append(f"Not yet reviewed against Euclid's enunciation: {links(unreviewed)}.")
    if reviewed:
        route = {k: [r for r in reviewed if records[r]["route"]["kind"] == k]
                 for k in ("euclid", "modified", "alternative")}
        if len(route["euclid"]) == len(reviewed):
            out.append("Every proof follows Euclid's argument, and each page notes where the "
                       "Lean departs from his sentences.")
        else:
            k = len(route["euclid"])
            parts = [f"{k} proof{'' if k == 1 else 's'} follow{'s' if k == 1 else ''} "
                     "Euclid's argument"]
            if route["modified"]:
                k = len(route["modified"])
                parts.append(f"{k} follow{'s' if k == 1 else ''} it with one step changed "
                             f"({links(route['modified'])})")
            if route["alternative"]:
                k = len(route["alternative"])
                parts.append(f"{k} {'argues' if k == 1 else 'argue'} differently "
                             f"({links(route['alternative'])})")
            out.append(and_list(parts) + "; each page says how.")
        overlap = [r for r in reviewed if "overlap" in records[r]]
        if overlap:
            out.append(overlap_sentences(overlap, facts, records, links, up))
    if postulate5 and len(proved) == count:
        out.append(postulate5_sentence(book, facts, proved))
    return " ".join(out)


