"""Build the readable pages from Heath's text, the Lean files, the mishnah, the
further reading, the review records (`review/<book>/NN.toml`) and `facts.json`, for
every book in `heath.BOOKS`:

    book/I/index.md    the book, proposition by proposition, after its introduction
                       (`mishnah/intro/I.md`), when that file exists
    book/I/front.md    its definitions (and Book I's postulates and common notions),
                       with their Lean
    book/I/NN.md       one page per proposition; after the mishnah, `reading/I/NN.md`
                       under "Further reading", when that file exists
    book/names.md      every proposition, porism and companion of every book, with its
                       Lean name, the module to import, its page and its certificate
    CERTIFICATE.md     what every proposition, porism and companion rests on, book by book
    GRAPH.md           who uses whom, book by book
    README.md          only the text between `<!-- scope:I -->` and `<!-- /scope:I -->`
                       (and likewise for each book): the book's completion summary
    docs/PROGRAM.md    only the status table between `<!-- status -->` and
                       `<!-- /status -->`, with the stage, the outside score and the
                       release read from `docs/program.toml`
    tracked Markdown   inline count values; generated_counts.py defines the markers
                       and where they are refused

Before it writes anything, the script checks the dated decision entries of
`docs/decisions/` (`decision_entries`): each is a page of its own, read where it is, and
nothing is assembled from them.

A page of a later book links each proposition it cites from an earlier one, as
[I.47](../I/47.md) on a page of Book II, and a porism to its anchor, as
[III.1 Por.](01.md#porism).

Three things are kept apart on every page and in the certificate: Heath's references
(the brackets in his translation, read from the text); the Lean's dependencies
(facts.json, computed by Lean); and the reconstruction of Euclid's argument (the review
records, written by a reviewer and tied to the commit read).

A page's listing names each declaration after the theorem by how the Lean uses it, its
comments aside: one of the theorems later propositions use, a lemma for the proposition's
own proofs, or a lemma beside the proposition; the Proof row names the companions in the
order the review record lists them; and the sentence on how to read the listing names a
step proved as a theorem of its own by that theorem's kind, a porism or a companion, and
stops on any other (`carried_ref`). On every run, before anything else, the script
checks all three against the cases of USE_CASES, ORDER_CASES and CARRIED_CASES
(`use_self_check`), and stops if one is read wrongly; MODERN_FIGURE_CASES
(`modern_figure_self_check`) checks that a modern figure follows its whole paragraph, or
is refused if that paragraph is missing, before any page is written.

Run after `lake env lean Certificate/Facts.lean`. Standard library, and Python 3.11 or
later for the review records (tomllib).
"""

