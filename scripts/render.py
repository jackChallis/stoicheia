def definitions_not_counted(refs, defs, book):
    """A line for a page where Heath's brackets give a definition that the Definitions
    row does not count: only Def. I.15, the circle's, is an assumption in Lean; the
    others his brackets give (Def. 10, the right angle, in I.11 to I.13; Def. 23,
    parallels, in I.27; Def. I.10 in III.1, III.3, III.9 and III.31; Book III's own
    Definitions 3, 4, 5 and 11) are said in Lean's own terms, which the line names, in
    one wording in every book. Definitions are written as heath_refs writes them, each
    with its book: "Def. I.10", "Def. III.4"."""
    # Lean's `DefinitionN` axioms are Book I's.
    counted = {("I", int(d.replace("Definition", ""))) for d in defs}
    parts = []
    for d in refs["Def."]:
        where, num = (book, d) if isinstance(d, int) else (d.split(".")[0], int(d.split(".")[1]))
        if (where, num) in counted:
            continue
        lean = DEFINITION_LEAN.get((where, num))
        lean = content_wording().get(lean, lean)
        parts.append(f"Def. {d} {lean}" if lean else f"Def. {d} is said in Lean's own terms")
    if not parts:
        return ""
    what = ("a definition rather than an assumption, so the row of definitions taken as "
            "axioms does not count it" if len(parts) == 1 else "definitions rather than "
            "assumptions, so the row of definitions taken as axioms does not count them")
    return "_Euclid's " + " and ".join(parts) + f", {what}._"


def tacit_key(book, up, cited, marked, unmarked):
    """The line that opens a page's list of tacit rules: what "(used here)" and
    "(through …)" mark, when the list marks them, and how the names in brackets are
    read. `cited`: the proof cites a proposition; `marked`: the list marks its rules;
    `unmarked`: some rule of the proof has neither mark, and comes in through a
    proposition it cites or a Common Notion (C.N. 3 and C.N. 5 rest on tacit rules)."""
    intro = "index.md" if book == "I" else "../I/index.md"
    rest = ("a proposition it cites or a Common Notion" if cited else "a Common Notion")
    used = ("_(used here) marks a rule this proof's own Lean calls, in the proof or a helper "
            "written for it; (through …) marks one its own Lean does not call but reaches "
            f"through the lemmas named, of [Book Zero]({up}Elements/Figure) or shared"
            + (", though a proposition it cites may rest on it too" if cited else "")
            + (f"; and a rule with no mark comes in only through {rest}. " if unmarked
               else ". ") if marked else "_")
    return (used + "The names in brackets are System E's: an Intersection rule says when "
            "straight lines and circles must meet, and an Intersections rule takes a point "
            f"where they do (see [Book I's introduction]({intro}))._")


def through_mark(lemmas, book, up):
    """A rule's mark in a page's list when its own Lean does not call it but reaches it
    through lemmas (facts.json's `inherited`), though a proposition it cites may rest on it
    too: "(through [`exists_between_nearer`](…))", each lemma linked to its line; after
    three, how many more."""
    named = [f"[`{step_name(s['name'], book)}`]({up}{s['file']}#L{s['line']})"
             for s in sorted(lemmas, key=lambda s: natural_key(step_name(s["name"], book)))]
    if len(named) > 3:
        more = len(named) - 3
        named = named[:3] + [f"{more} other lemma" + ("" if more == 1 else "s")]
    return f" (through {and_list(named)})"


def rules_summary(names, book):
    """Postulates, definitions and tacit rules in a few words, for a table cell, the
    kinds kept apart by semicolons, so that a count never reads as a postulate's number:
    "Postulates 1 and 3; Def. I.15; 9 tacit rules"; "none" for none."""
    posts = [a for a in names if a.startswith("Postulate")]
    defs = [a for a in names if a.startswith("Definition")]
    tacit = [a for a in names if a.startswith("Tacit.")]
    other = [a for a in names if a not in posts + defs + tacit]
    parts = []
    if posts:
        nums = roman_list(posts, "Postulate").split(", ")
        parts.append(("Postulate " if len(nums) == 1 else "Postulates ") + and_list(nums))
    if defs:
        parts.append(and_list(definition_list(defs, book).split(", ")))
    if tacit:
        parts.append(f"{len(tacit)} tacit rule" + ("" if len(tacit) == 1 else "s"))
    if other:
        parts.append(f"{len(other)} other axiom" + ("" if len(other) == 1 else "s"))
    return "; ".join(parts) if parts else "none"


def rests_on(p, docs, depth, book, refs, attached=()):
    """Markdown for the 'What it rests on' section. `refs` is Heath's references (see
    heath_refs); they come from the text, so they are shown before the Lean is done.
    `attached` is [(entry, refs)] for the porism and companions facts.json attaches to
    p: each gets a column of its own beside the proposition's, and a tacit rule found
    only beneath one of them is marked with its name, "(porism)"."""
    up = "../" * depth
    columns = [(p, refs)] + list(attached)
    if attached:
        labels = ["Proposition"] + [attached_label(a) for a, _ in attached]
        lines = ["| | " + " | ".join(labels) + " |", "|---|" + "---|" * len(labels)]
    else:
        lines = ["| | |", "|---|---|"]

    def row(name, cell):
        lines.append(f"| {name} | " + " | ".join(cell(e, r) for e, r in columns) + " |")

    row("Heath's references", lambda e, r: heath_refs_text(r, book) or "none")
    if not p or p["status"] == "sketched":
        return ("\n".join(lines) + "\n\n_Not yet proved in Lean, so what the Lean rests on "
                "is not yet known._\n")
    done = [(e, r) for e, r in columns if e["status"] != "sketched"]
    groups = {e["ref"]: axiom_groups(e) for e, _ in done}

    def lean(fn):
        return lambda e, r: fn(e) if e["ref"] in groups else "not yet proved"

    row("Lean cites", lean(lambda e: ", ".join(prop_link(c, book) for c in
                                               sorted(e["cites"], key=prop_key))
                           or "no propositions"))
    row("Postulates", lean(lambda e: roman_list(groups[e["ref"]][0], "Postulate") or "none"))
    row("Definitions taken as axioms",
        lean(lambda e: definition_list(groups[e["ref"]][1], book) or "none"))
    row("Common Notions", lean(lambda e: ", ".join(c.replace("C.N. ", "") for c in
                                                   sorted(set(e["common_notions"])))
                               or "none"))
    row("Tacit rules", lean(lambda e: f"{len(groups[e['ref']][2])} (listed below)"))
    if any(groups[e["ref"]][3] for e, _ in done):
        row("Other axioms", lean(lambda e: f"{len(groups[e['ref']][3])} (listed below)"))
    # What the proof uses itself, split (facts.json's `own_axioms` and `inherited`).
    row("Its own Lean calls", lean(lambda e: rules_summary(e["own_axioms"], book)))
    row("Through lemmas", lean(lambda e: rules_summary(list(e["inherited"]), book)))
    out = "\n".join(lines) + "\n"
    # One line for the shared steps of every column, each step named once.
    steps = {}
    for e, _ in done:
        for s in e.get("shared_steps", []):
            steps.setdefault(s["name"], s)
    steps = shared_steps_line({"shared_steps": list(steps.values())}, book, up)
    if steps:
        out += f"\n{steps}\n"
    out += f"\n{TABLE_KEY_EACH if attached else TABLE_KEY}\n"
    posts, defs, tacit, other = groups[p["ref"]]
    unlisted = definitions_not_counted(refs, defs, book)
    if unlisted:
        out += f"\n{unlisted}\n"
    if any(e["status"] == "proved-pending" for e, _ in done):
        out += ("\n_This proof is complete, but it cites propositions that are still "
                "only stated, so the list above will grow when they are proved._\n")
    # The rules beneath the proposition, then those found only beneath an attached entry.
    only = {}
    for e, _ in done[1:]:
        for a in groups[e["ref"]][2] + groups[e["ref"]][3]:
            if a not in p["axioms"]:
                only.setdefault(a, attached_mark(e))
    if tacit or other or only:
        by_kind = {}
        for a in tacit + [a for a in only if a.startswith("Tacit.")]:
            doc, path, line = docs.get(a, ("", "", 0))
            by_kind.setdefault(axiom_kind(path), []).append((a, doc, path, line))
        for a in other + [a for a in only if not a.startswith("Tacit.")]:
            doc, path, line = docs.get(a, ("", "", 0))
            by_kind.setdefault("Other", []).append((a, doc, path, line))
        rules = "tacit rule" if len(tacit) == 1 else "tacit rules"
        if other:
            rules += f" and {len(other)} other axiom" + ("" if len(other) == 1 else "s")
        # A rule the proof's own Lean calls is marked "(used here)", and one it inherits
        # names its lemmas. Any other comes in through a proposition it cites or a Common
        # Notion: C.N. 5 brings three laws of magnitude into I.1, which cites none. When
        # every rule listed is its own, none is marked.
        cited = bool(p["cites"])
        inherited = p["inherited"]
        unmarked = [a for a in tacit + other
                    if a not in p["own_axioms"] and a not in inherited]
        marked = any(a not in p["own_axioms"] for a in tacit + other)
        summary = f"The {len(tacit)} {rules} beneath this proof" + (
            ", counting those of the propositions it cites" if cited else "")
        if only:
            marks = sorted(set(only.values()), key=lambda m: m != "porism")
            where = " and ".join("its porism" if m == "porism" else m for m in marks)
            # Inside <summary>, Markdown's backticks are not read: write <code>.
            where = re.sub(r"`([^`]+)`", r"<code>\1</code>", where)
            summary += f", and {len(only)} more beneath {where}"
        out += f"\n<details><summary>{summary}</summary>\n\n"
        out += tacit_key(book, up, cited, marked, bool(unmarked)) + "\n\n"
        for kind in ["Reading the figure", "Lengths, angles and areas", "Superposition",
                     "Laws of magnitude", "Other"]:
            if kind not in by_kind:
                continue
            out += f"**{kind}**\n\n"
            for a, doc, path, line in sorted(by_kind[kind]):
                name = a.replace('Tacit.', '')
                if a in only:
                    here = f" ({only[a]})"
                elif not marked:
                    here = ""
                elif a in p["own_axioms"]:
                    here = " (used here)"
                elif a in inherited:
                    here = through_mark(inherited[a], book, up)
                else:
                    here = ""
                out += (f"- [`{name}`]({up}{path}#L{line}){here}: {doc}\n" if path else
                        f"- `{name}`{here}: not declared in `Elements/Foundations/`\n")
            out += "\n"
        out += "</details>\n"
    laws = cited_laws_table(p, docs, up)
    if laws:
        out += f"\n{laws}"
    return out


@functools.lru_cache(maxsize=None)
def law_docs():
    """law -> what it says: the docstring of each constructor of the `Cited` type, the laws
    a derivation inside a hypothetical placement may cite."""
    src = read_text(ROOT / "Elements" / "Foundations" / "Superposition" / "Syntax.lean")
    body = re.search(r"^inductive Cited where\n(.*?)^\s*deriving\b", src, re.M | re.S)
    if body is None:
        return {}
    return {m.group(2): " ".join(m.group(1).split())
            for m in re.finditer(r"/--((?:(?!-/).)*?)-/\s*\|\s*(\w+)", body.group(1), re.S)}


def cited_laws_table(p, docs, up):
    """The laws a derivation inside the placement cites (facts.json's `cited_laws`, on I.4
    and I.8): what each says, the theorem that proves it, linked where Lean says it is
    declared, and the construction rules beneath that proof. "" for an entry that cites
    none."""
    laws = (p or {}).get("cited_laws") or []
    if not laws:
        return ""

    def proof(found):
        name = found["name"]
        short = name.split(".", 1)[1] if name.startswith(("Superposition.", "BookI.")) else name
        return f"[`{short}`]({up}{found['file']}#L{found['line']})" if found["file"] \
            else f"`{short}`"

    def rule(name):
        _, path, line = docs.get(name, ("", "", 0))
        short = name.replace("Tacit.", "")
        return f"[`{short}`]({up}{path}#L{line})" if path else f"`{short}`"

    lines = ["**The laws cited inside the placement.** The derivation cites each law below as "
             "proved. Each is a statement about every figure, proved outside the placement, so "
             "citing it draws nothing there. The last column names the "
             f"[construction rules]({up}docs/FORMALIZATION.md#construction-rules) beneath its "
             "proof, as the certificate finds them (`cited_laws`).", "",
             "| Law | Proved by | Construction rules beneath the proof |", "|---|---|---|"]
    for law in laws:
        said = law_docs().get(law["law"], "")
        lines.append("| " + (f"{cell(said)} (`{law['law']}`)" if said else f"`{law['law']}`")
                     + " | " + (", ".join(proof(f) for f in law["proofs"]) or "none found")
                     + " | " + (", ".join(rule(r) for r in law["construction_rules"]) or "none")
                     + " |")
    return "\n".join(lines) + "\n"


# What the review record says, on the page (review/SCHEMA.md). Brief 0005, stage 1d.

NUMBER_WORDS = ["no", "one", "two", "three", "four", "five", "six", "seven", "eight",
                "nine", "ten"]


def number_word(k):
    return NUMBER_WORDS[k] if k < len(NUMBER_WORDS) else str(k)


ORDINAL_WORDS = ["", "first", "second", "third", "fourth", "fifth", "sixth", "seventh",
                 "eighth", "ninth", "tenth"]


def ordinal_word(k):
    if 0 < k < len(ORDINAL_WORDS):
        return ORDINAL_WORDS[k]
    suffix = "th" if k % 100 in (11, 12, 13) else {1: "st", 2: "nd", 3: "rd"}.get(k % 10, "th")
    return f"{k}{suffix}"


def and_list(items):
    """["a"] ↦ "a"; ["a", "b", "c"] ↦ "a, b and c"."""
    items = list(items)
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]


def clause(note):
    """A record's note as a clause within the line under the enunciation: without its
    closing full stop, so that " · " can follow."""
    return note.strip().rstrip(".")


def cell(text):
    """Text for a table cell: one line, its pipes escaped."""
    return " ".join(text.split()).replace("|", "\\|")


def overlap_rules(overlap):
    """The axioms an [overlap] names: its rule, then any it needs `also`."""
    return [overlap["rule"]] + overlap.get("also", [])


def overlap_rests(p, overlap):
    """Which rules its [overlap] names the proof rests on, from facts.json's `axioms`,
    in the record's order. Using some of the rules is distinct from using all or none."""
    return way_rests(p, overlap_rules(overlap))


def way_rests(p, rules):
    """Which of a combination's rules the proof rests on, from facts.json's `axioms`, in
    the combination's order."""
    axioms = (p or {}).get("axioms", [])
    return [r for r in rules if r in axioms]


def overlap_use(p, overlap):
    """A clause saying whether the proof uses all, some or none of the named rules. Of
    those it does not use, one is "does not use `b`", two "uses neither `b` nor `c`", and
    three or more "uses none of `b`, `c` and `d`", never "does not use `b` and `c`", which
    could be read as "not both"."""
    rules = overlap_rules(overlap)
    used = overlap_rests(p, overlap)
    if used == rules:
        return "our proof rests on " + ("the rule" if len(rules) == 1 else "all these rules")
    if not used:
        return "our proof does not use " + ("the rule" if len(rules) == 1 else "any of these rules")
    return "of these rules, our proof " + partial_use(used, [r for r in rules if r not in used])


def rule_names(rules):
    """The rules as the pages write them: `circle_eq`, without `Tacit.`."""
    return [f"`{r.removeprefix('Tacit.')}`" for r in rules]


def partial_use(used, unused):
    """What the proof does with a combination it uses only in part: "rests on `a` and does
    not use `b`", and for the rules unused, as `overlap_use` says them."""
    if len(unused) == 1:
        rest = f"does not use {rule_names(unused)[0]}"
    elif len(unused) == 2:
        rest = "uses neither {} nor {}".format(*rule_names(unused))
    else:
        rest = f"uses none of {and_list(rule_names(unused))}"
    comma = "," if len(used) > 1 else ""
    return f"rests on {and_list(rule_names(used))}{comma} and {rest}"


def overlap_ways(overlap):
    """Each combination of axioms that an [overlap] says contains the proposition: its rule
    with any it needs `also`, then each further one it lists in `ways`, which only a rule
    that states the proposition or gives it at once may have (heath.load_review)."""
    return [overlap_rules(overlap)] + overlap.get("ways", [])


def overlap_family(ways):
    """The kind of axiom the combinations name: "tacit rules" when every one is, else
    "axioms", as `overlap_word` says it of one combination."""
    return "tacit rules" if all(r.startswith("Tacit.") for w in ways for r in w) else "axioms"


def way_use(p, rules):
    """One of several combinations, its rules named, with which of them the proof rests on,
    from facts.json's `axioms`: "`a` and `b` together, of which our proof rests on `b` and
    does not use `a`"; "… of which our proof rests on both", or "uses neither"."""
    used = way_rests(p, rules)
    unused = [r for r in rules if r not in used]
    names = and_list(rule_names(rules))
    if len(rules) == 1:
        return f"{names}, " + ("on which our proof rests" if used else
                               "which our proof does not use")
    if not unused:
        return (f"{names} together, of which our proof rests on "
                + ("both" if len(rules) == 2 else f"all {number_word(len(rules))}"))
    if not used:
        return (f"{names} together, of which our proof uses "
                + ("neither" if len(rules) == 2 else "none"))
    return f"{names} together, of which our proof {partial_use(used, unused)}"


def overlap_ways_line(p, overlap):
    """What the line under the enunciation says of an [overlap] with `ways`, in a few
    words: how many combinations contain the proposition, and whether our proof rests on
    all, some or none of the rules of each, "our axioms already contain it in three ways,
    and our proof rests on some of the rules of each". Where that differs from one to
    another, each is taken by its place: "… rests on all the rules of the first, some of
    the rules of the second and none of the rules of the third". The Overlap row names
    the rules."""
    ways = overlap_ways(overlap)
    family = overlap_family(ways)
    count = number_word(len(ways))
    uses = ["all" if way_rests(p, w) == w else "some of" if way_rests(p, w) else "none of"
            for w in ways]
    if set(uses) == {"none of"}:
        return (f"our {family} contain it too, in {count} ways, though this proof uses none "
                "of their rules")
    if len(set(uses)) == 1:
        return (f"our {family} already contain it in {count} ways, and our proof rests on "
                f"{uses[0]} the rules of each")
    return (f"our {family} already contain it in {count} ways, and our proof rests on "
            + and_list(f"{u} the rules of the {ordinal_word(k)}" for k, u in enumerate(uses, 1)))


def overlap_ways_clause(p, overlap):
    """The combinations of an [overlap] with `ways`, each with the rules our proof rests on
    (`way_use`), for the book's summary: "in three ways: …; …; and …"."""
    ways = [way_use(p, w) for w in overlap_ways(overlap)]
    return f"in {number_word(len(ways))} ways: " + "; ".join(ways[:-1]) + "; and " + ways[-1]


def overlap_contains_ways(p, overlap, what):
    """What the book's summary says of an [overlap] with `ways`: our rules "already
    contain" `what` in each way, or, where the proof uses none of the rules of any,
    "contain it too"."""
    ways = overlap_ways(overlap)
    family = overlap_family(ways)
    if any(way_rests(p, w) for w in ways):
        return f"our {family} already contain {what} {overlap_ways_clause(p, overlap)}"
    return f"our {family} contain {what} too, {overlap_ways_clause(p, overlap)}"


def overlap_steps(overlap):
    """Does the rule only supply a step of a proof of the proposition, the overlap
    catalogue's third kind (`kind = "step"`), rather than state the proposition or give
    it at once? Only then do the pages say "supplies a step" in place of "contains".
    Every [overlap] names its kind (heath.load_review rejects one that does not), so
    nothing is worded by a guess."""
    return overlap["kind"] == "step"


def overlap_word(overlap):
    """What contains the proposition, or supplies a step of a proof of it, as the top
    line says it: "one of our tacit rules", "two of our tacit rules together"."""
    rules = overlap_rules(overlap)
    kind = "tacit rules" if all(r.startswith("Tacit.") for r in rules) else "axioms"
    if len(rules) == 1:
        return f"one of our {kind}"
    return f"{number_word(len(rules))} of our {kind} together"


def representation_badge(record):
    """A few words beside the badge for a representation that changes how the whole
    statement is read (review/terms.toml `badge`): "in our measure of circumferences"."""
    terms = load_terms()
    tags = (record.get("representation") or {}).get("tags", [])
    badges = [terms[t]["badge"] for t in tags if "badge" in terms.get(t, {})]
    return and_list(badges) if badges else ""


def in_lean_line(p, record, book, n):
    """The line under the enunciation, from the review record, short enough to read at
    a glance: whether the proof is finished, what its statement covers, whose argument it
    follows, and whether an axiom already contains the proposition or supplies a step of
    a proof of it, as the record's [overlap] `kind` says. The detail is in the
    field table under "In Lean"; the reader meets the scope before the green check means
    anything more than it says."""
    status = p["status"] if p else "sketched"
    head = STATUS_LINE[status]
    if record is None:
        return f"**In Lean:** {head} · not yet reviewed against Euclid's enunciation"
    st, route = record["statement"], record["route"]
    short = clause(st.get("short", ""))
    if st["scope"] == "full":
        badge = representation_badge(record)
        first = f"{head}, as Euclid states it" + (f", {badge}" if badge else "")
    elif st["scope"] == "restricted":
        first = f"{head} for a restricted statement ({short})"
    else:
        first = f"{head} in part: {short}"
    parts = [first]
    if status != "sketched":
        parts.append({"euclid": whose(book, n),
                      "modified": f"{whose(book, n)}, with one step changed",
                      "alternative": "a different argument"}[route["kind"]])
    if "overlap" in record:
        ov = record["overlap"]
        rules = overlap_rules(ov)
        used = overlap_rests(p, ov)
        one = len(rules) == 1
        rule = "the rule" if one else "the rules"
        if len(overlap_ways(ov)) > 1:
            parts.append(f"{overlap_ways_line(p, ov)} (see Overlap)")
        elif used and used != rules:
            claim = ("supply a step of a proof of it" if overlap_steps(ov)
                     else "already contain it")
            parts.append(f"{overlap_word(ov)} {claim}; {overlap_use(p, ov)} (see Overlap)")
        elif overlap_steps(ov):
            verb = "supplies" if one else "supply"
            if used:
                parts.append(f"{overlap_word(ov)} {verb} a step of a proof of it, and our "
                             f"proof rests on {rule} (see Overlap)")
            else:
                parts.append(f"{overlap_word(ov)} {verb} a step of a proof of it, though our "
                             f"proof does not use {rule} (see Overlap)")
        else:
            verb = "contains" if one else "contain"
            if used:
                parts.append(f"{overlap_word(ov)} already {verb} it (see Overlap)")
            else:
                parts.append(f"{overlap_word(ov)} {verb} it too, though this proof does not "
                             f"use {'it' if one else 'them'} (see Overlap)")
    return "**In Lean:** " + " · ".join(parts)


def proof_cell(p, attached, order=()):
    """The Proof row: the proposition's status, and its porism's and companions'. Those
    that share the proposition's status come first, the porism and then the companions
    together, in one clause, in the order the review record lists them (`order`,
    references such as "I.45 apart", or "I. 45 apart" with Heath's spacing); then each
    whose status differs, with its own, so
    that a porism's status is never read as the companions'."""
    if not p:
        return STATUS["sketched"]
    text = STATUS[p["status"]]
    same, other = [], []
    rank = {heath.parse_ref(ref): i for i, ref in enumerate(order)}
    attached = sorted(attached, key=lambda a: (heath.parse_ref(a["ref"]).kind != "porism",
                                               rank.get(heath.parse_ref(a["ref"]), len(rank))))
    for a in attached:
        r = heath.parse_ref(a["ref"])
        link = prop_link(a["ref"], r.book)
        if r.kind == "porism":
            if a["status"] == p["status"]:
                text += f", and its porism, {link}"
            else:
                other.append(f"; its porism, {link}: {STATUS[a['status']]}")
        elif a["status"] == p["status"]:
            same.append(f"`Prop{r.n}.{r.name}` ({link})")
        else:
            other.append(f"; its companion `Prop{r.n}.{r.name}`, {link}: {STATUS[a['status']]}")
    if same:
        text += f", and its companion{'s' if len(same) > 1 else ''} {and_list(same)}"
    return text + "".join(other)


def field_table(book, n, p, record, attached, docs):
    """The table under "## In Lean": proof, statement, extra hypotheses, argument,
    representation, overlap and the review, each row from facts.json or the record."""
    order = (record or {}).get("statement", {}).get("companions", [])
    rows = [("Proof", proof_cell(p, attached, order))]
    if record is None:
        rows.append(("Reviewed", "not yet: the statement has not been read against "
                                 "Euclid's enunciation"))
    else:
        st, route = record["statement"], record["route"]
        note = st.get("note", "")
        rows.append(("Statement", {"full": "The whole enunciation.",
                                   "restricted": "Restricted.",
                                   "partial": "In part."}[st["scope"]]
                     + (f" {note}" if note else "")))
        if st["hypotheses"]:
            # One to a line: a hypothesis may have a semicolon of its own (I.40).
            rows.append(("Extra hypotheses", "<br>".join(st["hypotheses"])))
        own = "The argument Heath prints" if heath.bracketed(book, n) else "Euclid's"
        rows.append(("Argument", {"euclid": f"{own}.",
                                  "modified": f"{own}, with one step changed.",
                                  "alternative": "A different argument."}[route["kind"]]
                     + (f" {route['note']}" if route.get("note") else "")))
        rep = record.get("representation")
        if rep:
            terms = load_terms()
            meanings = [terms[t]["meaning"] for t in rep["tags"]
                        if terms.get(t, {}).get("kind") == "representation"]
            text = rep.get("note") or " ".join(meanings)
            if text:
                rows.append(("Representation", text))
        if "overlap" in record:
            ov = record["overlap"]

            def linked(rule):
                doc, path, line = docs.get(rule, ("", "", 0))
                name = f"`{rule.replace('Tacit.', '')}`"
                return f"[{name}](../../{path}#L{line})" if path else name

            names = [linked(rule) for rule in overlap_rules(ov)]
            name = and_list(names)
            one = len(names) == 1
            note = ov.get("note")
            ways = overlap_ways(ov)
            if len(ways) > 1:
                # Each combination's rules, then the note; then, as for one combination,
                # which rules our proof rests on, for each it uses only in part.
                each = [and_list(linked(rule) for rule in w) for w in ways]
                text = (f"{number_word(len(ways)).capitalize()} ways: " + "; ".join(each[:-1])
                        + "; and " + each[-1] + ". "
                        + (note or "Each way's rules together already contain this proposition."))
                for k, w in enumerate(ways, 1):
                    used = way_rests(p, w)
                    if used and used != w:
                        text += (f" Of the {ordinal_word(k)} way's rules, our proof "
                                 f"{partial_use(used, [r for r in w if r not in used])}.")
            elif note:
                text = f"{name}: {note}"
            elif overlap_steps(ov):  # heath.py asks a note of a step; this is a fallback
                text = (f"{name} {'supplies' if one else 'supply'} a step of a proof of this "
                        "proposition.")
            else:
                text = f"{name} already {'contains' if one else 'contain'} this proposition."
            used = overlap_rests(p, ov)
            if len(ways) == 1 and used and used != overlap_rules(ov):
                use = overlap_use(p, ov)
                text += f" {use[0].upper()}{use[1:]}."
            if optional_path(ROOT / "docs" / "reports" / "overlaps.md") is not None:
                text += " See [the overlap catalogue](../../docs/reports/overlaps.md)."
            rows.append(("Overlap", text))
        rv = record["review"]
        what = {"exceptions": "The statement and the argument read against Heath's text, for "
                              "every departure from Euclid",
                "full": "The statement and every passage of the argument read against "
                        "Heath's text"}[rv["stage"]]
        commit = rv.get("commit")
        at = (f", at commit [`{commit}`]({REPO}/commit/{commit})" if commit
              else ", not yet stamped with a commit")
        rows.append(("Reviewed", f"{what}{at} ([the record](../../review/{book}/{n:02d}.toml))"))
    return "\n".join(["| | |", "|---|---|"] + [f"| {k} | {cell(v)} |" for k, v in rows])


def clause_map(record):
    """For a statement in part, the clause map from [coverage], shown
    before the Lean: what the Lean checks, what it proves toward the clauses it leaves
    out, and what stays in Euclid's words."""
    cov = record.get("coverage") if record else None
    if not cov:
        return ""
    out = ["**What the Lean proves, clause by clause**", ""]
    for key, label in (("checked", "Checked in Lean:"),
                       ("explains", "What the Lean proves toward the clauses it leaves out:"),
                       ("text_only", "Kept in Euclid's words and the mishnah only:")):
        if cov[key]:
            out.append(f"- {label}")
            out += [f'  - "{c}"' if key == "text_only" else f"  - {c}" for c in cov[key]]
    return "\n".join(out)


# The plain words that lead each note under "How the Lean follows the text", one for each
# kind of passage in review/SCHEMA.md. A helper's word names it ("Done by `Prop6.less`"),
# and a porism or a companion proved as its own theorem is "Proved separately, as
# `Prop16.porism`"; the sentence above the list names it by its kind (`carried_ref`).
PASSAGE_WORD = {"carried": "Carried", "helper": "Done by a lemma", "grouped": "Carried together",
                "case": "A further case", "given": "Already given",
                "different": "Argued another way", "unformalized": "Left in Euclid's words"}
# How the sentence above the list names what it marks, kind by kind.
PASSAGE_PHRASE = {
    "helper": "where a lemma does a step Euclid takes for granted",
    "grouped": "where several sentences share one step",
    "case": "where the Lean takes a case Euclid's figure leaves aside",
    "given": "where the statement already gives a step",
    "different": "where a step is argued another way",
    "carried": "where a step needs a word of its own",
}


def plain_text(paragraphs):
    """Heath's paragraphs as one line of plain words, as review records quote them."""
    return heath.normalize(" ".join(paragraphs).replace("*", ""))


def first_words(at, proof_text=""):
    """A passage's first words, as the page quotes them: with Heath's full stop when
    they end his sentence in `proof_text`, and with "…" when they stop within it."""
    at = heath.normalize(at.replace("*", ""))
    if at[-1] in ".?!":
        return at
    i = proof_text.find(at)
    after = proof_text[i + len(at):i + len(at) + 1] if i >= 0 else ""
    return at + after if after in (".", "?", "!") else at + "…"


def passage_notes(record, proof_text=""):
    """The record's [[passage]] notes, a short list keyed to the first words of each
    passage, shown just above the listing. Each note opens with a plain word for its kind
    (PASSAGE_WORD): where a lemma does a step, sentences are carried together, the Lean
    takes a further case, the statement already gives a step, the argument goes another
    way, or a passage is left in Euclid's words."""
    passages = record["passage"] if record else []
    if not passages:
        return ""
    out = ["**How the Lean follows the text**", ""]
    for q in passages:
        word = PASSAGE_WORD[q["kind"]]
        helper = q.get("helper")
        if helper and q["kind"] == "helper":
            # A helper may be a lemma, a proposition or an axiom (III.25's `Postulate5`).
            word = f"Done by `{helper}`"
        elif helper and q["kind"] == "carried":
            word = f"Proved separately, as `{helper}`"
        elif helper:
            word = f"{word}, by `{helper}`"
        note = f" {q['note']}" if q.get("note") else ""
        out.append(f'- **{word}.** "{first_words(q["at"], proof_text)}"{note}')
    return "\n".join(out)


def carried_ref(p, helper):
    """The theorem a carried passage of the proposition entry p is proved separately as:
    the entry of p's `attached` that `helper` names, as `Prop16.porism`,
    `BookIII.Prop16.porism` or `Elements.BookIII.Prop16.porism`, taken apart by
    `heath.parse_ref`, so that its `kind` is "porism" or "companion" and two names for one
    theorem give one Ref. Any other helper stops the render: a lemma or a proposition that
    does a step makes a `helper` passage, "Done by" it, and has no entry of its own under p
    to be proved separately as (review/SCHEMA.md)."""
    for ref in p.get("attached", []):
        r = heath.parse_ref(ref)
        if helper in (f"Prop{r.n}.{r.name}", f"Book{r.book}.Prop{r.n}.{r.name}", r.lean):
            return r
    raise SystemExit(f"{p['ref']}: a carried passage names `{helper}`, which is not its "
                     "porism or one of its companions in facts.json, in one of the three ways "
                     "render.py reads such a name: `Prop16.porism`, `BookIII.Prop16.porism` or "
                     "`Elements.BookIII.Prop16.porism`. A lemma or a proposition that does a "
                     "step makes a `helper` passage (review/SCHEMA.md)")


def how_to_read(p, record, proof_text=""):
    """The sentence under the field table on how to read the listing. It says the lines
    under each sentence carry it out only where that is so: a passage the Lean does not
    carry out is named. The list below it is said to mark only what it marks, kind by
    kind, and the smaller adjustments are left to the `/- … -/` notes in the listing."""
    if not p or p["status"] == "sketched":
        return ("Euclid's sentences are the `--` comments, and our own notes are in `/- … -/`. "
                "The Lean that will carry each sentence out is still to be written; `sorry` is "
                "Lean's word for a step not yet taken.")
    how = ("Euclid's sentences are the `--` comments, and our own notes are in `/- … -/`; "
           "the lines under each sentence are the Lean that carries it out")
    passages = record["passage"] if record else []
    left = [q for q in passages if q["kind"] == "unformalized"]
    if len(left) == 1:
        where = first_words(left[0]["at"], proof_text)
        how += f', except the passage from "{where}", which the Lean does not carry out'
    elif left:
        how += (f", except {number_word(len(left))} passages the Lean does not carry out")
    how += "."
    if not passages:
        return how
    marks = [PASSAGE_PHRASE[k] for k in PASSAGE_PHRASE if k != "carried"
             and any(q["kind"] == k for q in passages)]
    carried = [q for q in passages if q["kind"] == "carried"]
    if any(not q.get("helper") for q in carried):
        marks.append(PASSAGE_PHRASE["carried"])
    # Counted by theorem, not by passage: one companion carrying two passages, or named two
    # ways, is still one companion.
    kinds = [r.kind for r in {carried_ref(p, q["helper"]) for q in carried if q.get("helper")}]
    if kinds:
        each = [f"a {k}" if kinds.count(k) == 1 else f"{number_word(kinds.count(k))} {k}s"
                for k in heath.KINDS if k in kinds]
        own = ("is proved as a theorem of its own" if len(kinds) == 1
               else "are proved as theorems of their own")
        marks.append(f"where {and_list(each)} {own}")
    if left:
        marks.append("where the Lean stops")
    return (how + f" The list below marks {and_list(marks)}; the `/- … -/` notes in the "
            "listing explain smaller adjustments.")


