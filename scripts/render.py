# Unicode's default-ignorable characters that are no format characters (Cf): the
# combining grapheme joiner, the Hangul fillers, two Khmer vowels, the Mongolian and
# other variation selectors, and the code points Unicode keeps for more of them.
IGNORABLE = ((0x034F, 0x034F), (0x115F, 0x1160), (0x17B4, 0x17B5), (0x180B, 0x180F),
             (0x2065, 0x2065), (0x3164, 0x3164), (0xFE00, 0xFE0F), (0xFFA0, 0xFFA0),
             (0xFFF0, 0xFFF8), (0xE0000, 0xE0FFF))
# Characters that render blank though Unicode counts them neither white space nor
# default-ignorable: a fixed list, since Unicode has no property for a blank glyph. The
# Braille pattern blank, the musical symbol null notehead and the Khitan small script
# filler (scripts/safe_push.py's BLANK_GLYPHS).
BLANK_GLYPHS = frozenset("\u2800\U0001d159\U00016fe4")


def invisible(char):
    """Is `char` one that an entry, or the folder's README, may not hold? A control
    character but a tab and a line feed (a carriage return among them), a format character
    (Unicode's Cf, as a zero-width space or a byte-order mark), a line or paragraph
    separator, another default-ignorable character (IGNORABLE), a character of the fixed
    list BLANK_GLYPHS, which render blank, or a code point Unicode keeps for private use or
    leaves unassigned (its Co and Cn, as this Python's Unicode data has them), which no
    font is bound to draw. Each could hide a copy of an older entry from
    scripts/safe_push.py's comparison, or make Git and a reader see different lines;
    safe_push.py refuses the same characters."""
    category = unicodedata.category(char)
    return ((category == "Cc" and char not in "\t\n")
            or category in ("Cf", "Zl", "Zp", "Co", "Cn") or char in BLANK_GLYPHS
            or any(a <= ord(char) <= b for a, b in IGNORABLE))


def printable_text(text):
    """A name read from the disk, with every character that Python counts unprintable,
    control and format characters among them, written as an escape, so that a refusal
    that prints it gives a terminal nothing to act on (scripts/safe_push.py's
    printable_text)."""
    return "".join(c if c.isprintable() else c.encode("unicode_escape").decode("ascii")
                   for c in text)


def folded(name):
    """`name` as a Mac's file system compares names: in Unicode's NFD form, casefolded
    (scripts/safe_push.py's spelled_otherwise reads names so)."""
    return unicodedata.normalize("NFD", unicodedata.normalize("NFD", name).casefold())


def spelled_otherwise(path):
    """The names on disk of the first part of `path`, below ROOT, that the disk spells
    otherwise, or beside which it holds a name that differs from it only as `folded`
    reads names; None when there is none. A file system that ignores case, as a Mac's
    does, finds docs/Decisions/, or docs/deciſions/ with a long s, as docs/decisions/; Git
    and GitHub do not."""
    here = ROOT
    for part in path.relative_to(ROOT).parts:
        if not here.is_dir():
            return None
        names = sorted(name for name in os.listdir(here) if folded(name) == folded(part))
        if names and names != [part]:
            return [printable_text((here / name).relative_to(ROOT).as_posix())
                    for name in names]
        here = here / part
    return None


def ignore_sources(cannot):
    """The real paths of the files, beside the root's .gitignore, whose rules may pass a
    file of docs/decisions/ over (git_ignored): this repository's .git/info/exclude, where
    `git rev-parse --git-path` finds it, and the user's excludes file, core.excludesFile
    or, where that is unset, Git's own default, $XDG_CONFIG_HOME/git/ignore or
    ~/.config/git/ignore. A path Git gives relative is read from ROOT, as Git reads it
    here. If Git cannot say, render.py stops."""
    def ask(*args):
        try:
            return subprocess.run(["git", *args], cwd=ROOT, capture_output=True)
        except OSError as error:
            raise SystemExit(cannot.format(error)) from None

    exclude = ask("rev-parse", "--git-path", "info/exclude")
    configured = ask("config", "--path", "--get", "core.excludesFile")
    if exclude.returncode != 0 or configured.returncode not in (0, 1):
        raise SystemExit(cannot.format("git could not name info/exclude or "
                                       "core.excludesFile"))
    paths = [os.fsdecode(exclude.stdout).removesuffix("\n")]
    if configured.returncode == 0:
        paths.append(os.fsdecode(configured.stdout).removesuffix("\n"))
    elif os.environ.get("XDG_CONFIG_HOME"):
        paths.append(os.path.join(os.environ["XDG_CONFIG_HOME"], "git", "ignore"))
    elif "HOME" in os.environ:
        paths.append(os.path.join(os.environ["HOME"], ".config", "git", "ignore"))
    return {os.path.realpath(os.path.join(ROOT, path)) for path in paths}


def git_ignored(names):
    """Those of `names`, the files of docs/decisions/, that Git ignores (`git
    check-ignore -v`) by a rule of the root's .gitignore, of .git/info/exclude or of the
    user's own excludes file (ignore_sources), as Finder's .DS_Store is: untracked, and
    never committed, so no part of the decisions record; a tracked file is never ignored.
    A file ignored by a rule of a nested .gitignore, which a commit may add beside the
    folder or in it, or whose last matching rule is a negated one (!), is not passed over.
    Git's work tree must be ROOT. If Git cannot be run, cannot answer, answers in a form
    it was not asked for, or names a file it was not asked about, render.py stops, so
    that no file is passed over on a guess."""
    if not names:
        return set()
    asked = {f"docs/decisions/{name}": name for name in names}
    cannot = ("docs/decisions: cannot ask Git which files it ignores ({}); a checkout, or "
              "GIT_DIR and GIT_WORK_TREE, is needed")
    try:
        top = subprocess.run(["git", "rev-parse", "--show-toplevel"], cwd=ROOT,
                             capture_output=True, check=True)
    except (subprocess.CalledProcessError, OSError) as error:
        raise SystemExit(cannot.format(error)) from None
    work_tree = os.fsdecode(top.stdout).removesuffix("\n")
    if os.path.realpath(work_tree) != os.path.realpath(ROOT):
        raise SystemExit(f"docs/decisions: Git's work tree {work_tree} is not the "
                         f"repository root {ROOT}, so Git cannot say which files it ignores")
    try:
        result = subprocess.run(["git", "check-ignore", "-v", "-z", "--stdin"], cwd=ROOT,
                                input=b"".join(os.fsencode(path) + b"\0" for path in asked),
                                capture_output=True)
    except OSError as error:
        raise SystemExit(cannot.format(error)) from None
    if result.returncode not in (0, 1):
        raise SystemExit("docs/decisions: git check-ignore failed: "
                         + os.fsdecode(result.stderr).strip())
    # Each file Git finds a rule for: the rule's source, its line, its pattern, the file.
    fields = [os.fsdecode(field) for field in result.stdout.split(b"\0")]
    if fields[-1] or (len(fields) - 1) % 4:
        raise SystemExit("docs/decisions: git check-ignore answered in a form it was not "
                         "asked for")
    ignored, sources = set(), None
    for i in range(0, len(fields) - 1, 4):
        source, _, pattern, path = fields[i:i + 4]
        if path not in asked:
            raise SystemExit("docs/decisions: git check-ignore named a file it was not "
                             "asked about")
        if pattern.startswith("!"):
            continue
        if sources is None:
            sources = ignore_sources(cannot)
        if source == ".gitignore" or os.path.realpath(os.path.join(ROOT, source)) in sources:
            ignored.add(asked[path])
    return ignored


def decision_entries():
    """Check docs/decisions/, the folder of dated decision entries, and return the
    entries' names. Each entry is a page of its own, read where it is, and nothing is
    assembled from them: so an entry may hold whatever a page may, headings included, and
    needs no date heading, since its name carries its date. The folder may be absent.
    Where it is not, it is a folder under no link, spelled so on disk with nothing beside
    it spelled otherwise, and holds regular files alone: its README.md, which is no entry,
    and entries named `<YYYY-MM-DD>-<slug>.md`, a valid date no earlier than FIRST_ENTRY
    and then lower-case letters and digits joined by hyphens. A file Git ignores by a rule
    of the root's .gitignore, .git/info/exclude or the user's excludes file, as Finder's
    .DS_Store, is passed over (git_ignored). Every file there is UTF-8, holds no count
    marker, so that render.py writes nothing into the folder, and holds no character that
    `invisible` refuses; and every entry holds text. A refusal prints a name with its
    unprintable characters written as escapes (printable_text). The working tree has no
    commit date, so no date is too late here: the pre-flight's guard of the entries
    refuses one later than the day after the earlier of its commit's and the runner's
    (scripts/safe_push.py, entry_changes)."""
    try:
        folder = generated_counts.repository_path(ROOT, ROOT / "docs" / "decisions")
    except ValueError as error:
        raise SystemExit(f"docs/decisions: expected a folder of entry files: {error}") from None
    spellings = spelled_otherwise(folder)
    if spellings:
        raise SystemExit(f"docs/decisions: spelled on disk as {', '.join(spellings)}; "
                         "Git and GitHub tell names apart by case, so it must be "
                         "docs/decisions alone")
    if not folder.exists():
        return []
    if not folder.is_dir():
        raise SystemExit("docs/decisions: expected a folder of entry files")
    entries, names = [], sorted(os.listdir(folder))
    ignored = git_ignored(names)
    for name in names:
        if name in ignored:
            continue
        where, path = f"docs/decisions/{printable_text(name)}", folder / name
        if path.is_symlink() or not path.is_file():
            raise SystemExit(f"{where}: expected a regular file, the README.md or an entry")
        match = DECISION_FILE.fullmatch(name)
        if name != "README.md" and not match:
            raise SystemExit(f"{where}: expected README.md or an entry named "
                             "<YYYY-MM-DD>-<slug>.md, a date and then lower-case letters "
                             "and digits joined by hyphens")
        if match:
            try:
                day = date.fromisoformat(match.group(1))
            except ValueError:
                raise SystemExit(f"{where}: invalid date") from None
            if day < FIRST_ENTRY:
                raise SystemExit(f"{where}: dated before {FIRST_ENTRY}, the day the entries "
                                 "began")
        try:
            text = path.read_bytes().decode("utf-8")
        except UnicodeDecodeError as error:
            raise SystemExit(f"{where}: not UTF-8 text (byte {error.start}: "
                             f"{error.reason})") from None
        try:
            counts = generated_counts.markers(text, where)
        except ValueError as error:
            raise SystemExit(f"{error}; count markers are forbidden in dated history, "
                             "which render.py never writes") from None
        if counts:
            number = text.count("\n", 0, counts[0].start) + 1
            raise SystemExit(f"{where}:{number}: count markers are forbidden in dated "
                             "history, which render.py never writes")
        if match and not text.strip():
            raise SystemExit(f"{where}: expected the entry's text")
        for number, line in enumerate(text.split("\n"), 1):
            hidden = next((char for char in line if invisible(char)), None)
            if hidden is not None:
                named = unicodedata.name(hidden, "")
                raise SystemExit(f"{where}:{number}: U+{ord(hidden):04X}"
                                 f"{f' ({named})' if named else ''}: "
                                 f"{'an entry' if match else 'the README'} holds no "
                                 "control character but a tab and a line feed, no format "
                                 "character, no line or paragraph separator, no other "
                                 "default-ignorable character, no character that renders "
                                 "blank and no private-use or unassigned code point, any of "
                                 "which could hide a copy of an older entry")
        if match:
            entries.append(name)
    return entries


def heath_edges(book, count):
    """The arrows of a book's graph from Heath's references: a (cited, citing) pair of
    propositions for each earlier proposition that a proposition's enunciation or proof
    refers to in Heath's brackets (I.22's [I. 20] is in its enunciation). "[III. 1, Por.]"
    is drawn from III.1, as heath.citations reads it."""
    edges = set()
    for n in range(1, count + 1):
        _, enunciation, proof = heath.read(book, n)
        edges |= {(c, f"{book}.{n}") for c in heath.citations([enunciation] + proof)
                  if c != f"{book}.{n}"}
    return edges


def lean_edges(facts, book):
    """The arrows of a book's graph from the Lean: a (cited, citing) pair of propositions
    for each entry of facts.json that a proposition of the book, its porism or a
    companion cites (`cites`). A porism or companion is drawn as its proposition, both
    citing and cited, so III.17's use of "III.16 Por." is an arrow from III.16, and III.1
    Por.'s use of III.1 is no arrow at all."""
    edges = set()
    for p in facts.values():
        citing = heath.parse_ref(p["ref"]).parent
        if citing.split(".")[0] != book:
            continue
        edges |= {(heath.parse_ref(c).parent, citing) for c in p["cites"]
                  if heath.parse_ref(c).parent != citing}
    return edges


def edge_order(edge):
    """Arrows in the order of the proposition they reach, then of the one they leave."""
    cited, citing = edge
    return prop_key(citing), prop_key(cited)


def node(ref):
    """A proposition's name in a Mermaid graph: I.47 is `I47`."""
    return ref.replace(".", "")


def mermaid(book, count, facts, edges, dashed=frozenset()):
    """One book's graph: its propositions, green when proved in Lean and grey when only
    stated; the propositions of earlier books that an arrow leaves, white; and the arrows,
    those in `dashed` dashed."""
    earlier = sorted({c for c, _ in edges if c.split(".")[0] != book}, key=prop_key)
    out = ["```mermaid", "graph TD"]
    out += [f'  {node(c)}["{c}"]' for c in earlier]
    out += [f'  {book}{n}["{book}.{n}"]' for n in range(1, count + 1)]
    out += [f"  {node(c)} {'-.->' if (c, d) in dashed else '-->'} {node(d)}"
            for c, d in sorted(edges, key=edge_order)]
    out.append("  classDef proved fill:#d4edda,stroke:#2e7d32,color:#1b5e20")
    out.append("  classDef sketched fill:#eeeeee,stroke:#9e9e9e,color:#424242")
    if earlier:
        out.append("  classDef earlier fill:#ffffff,stroke:#9e9e9e,color:#424242")
        out.append(f"  class {','.join(node(c) for c in earlier)} earlier")
    proved = [f"{book}{n}" for n in range(1, count + 1)
              if facts.get(f"{book}.{n}", {}).get("status") in ("proved", "proved-pending")]
    sketched = [f"{book}{n}" for n in range(1, count + 1) if f"{book}{n}" not in proved]
    if proved:
        out.append(f"  class {','.join(proved)} proved")
    if sketched:
        out.append(f"  class {','.join(sketched)} sketched")
    return out + ["```"]


def arrows(k):
    return f"{k} arrow" + ("" if k == 1 else "s")


def page_link(ref):
    """A proposition's page, linked from GRAPH.md at the top of the repository."""
    b, n = ref.split(".")
    return f"[{ref}](book/{b}/{int(n):02d}.md)"


GRAPH_SECTIONS = ("From Heath's references", "From the Lean")
# Heath's own word on the brackets, from his chapter on Euclid in Arabia (vol. 1, p. 83).
HEATH_ON_BRACKETS = ("\"such specific quotations of earlier propositions are rare in "
                     f"Euclid\" (vol. 1, p. 83, [scan leaf n103]({scan_url('1', 'n103')}))")


def earlier_table(book, count, earlier, heath_side):
    """Under a later book's graph from the Lean: for each proposition, the propositions
    of earlier books its proof cites, and which of them Heath's brackets give too."""
    rows = ["<details><summary>The propositions of earlier books that each proof cites"
            "</summary>", "",
            "| Proposition | Lean cites | Of these, among Heath's references |",
            "|---|---|---|"]
    for n in range(1, count + 1):
        ref = f"{book}.{n}"
        cited = sorted({c for c, d in earlier if d == ref}, key=prop_key)
        if not cited:
            continue
        heaths = [c for c in cited if (c, ref) in heath_side]
        rows.append(f"| {page_link(ref)} | {', '.join(cited)} | {', '.join(heaths) or 'none'} |")
    return rows + ["", "</details>"]


def graph(facts):
    """GRAPH.md: for each book, a graph from Heath's references and one from the Lean,
    with the counts that tie them together, which are checked to add up."""
    contents = []
    for i, book in enumerate(BOOKS):
        # GitHub numbers the second heading of a name "-1", the third "-2".
        suffix = f"-{i}" if i else ""
        contents.append(f"Book {book}: [from Heath's references](#from-heaths-references"
                        f"{suffix}), [from the Lean](#from-the-lean{suffix})")
    out = [GENERATED, "# Who uses whom", "",
           "Two graphs for each book, in which each arrow runs from a proposition to one "
           "that uses it, and a porism is drawn as its proposition. Green: proved in Lean; "
           "grey: stated in Lean, not yet proved; white: a proposition of an earlier book.",
           "",
           "- **From Heath's references.** An arrow for each earlier proposition that "
           "Heath's translation names in square brackets, such as \"[I. 4]\", in a "
           "proposition's enunciation or proof. The brackets are Heath's editorial "
           "references, not Euclid's words: as Heath says, " + HEATH_ON_BRACKETS + ". A "
           "missing bracket does not mean that Euclid gave no reason, and a bracket is "
           "Heath's pointer, not a checked reconstruction of the argument.",
           "- **From the Lean.** An arrow for each proposition that a proof in Lean cites, "
           "as [the certificate](CERTIFICATE.md) records it. Solid arrows are also among "
           "Heath's references; dashed ones only the Lean draws. Most dashed arrows come "
           "from shared steps, lemmas proved once and used by many proofs, which bring in "
           "the propositions they rest on ([the certificate](CERTIFICATE.md#shared-steps) "
           "says more). For each book after Book I the graph draws only the book's own "
           "propositions, and a table under it lists the earlier propositions each proof "
           "cites. A line under the graph names any of Heath's references that the Lean "
           "does not cite.", "",
           " · ".join(contents), ""]
    for book, (count, titles) in BOOKS.items():
        heath_side = heath_edges(book, count)
        lean_side = lean_edges(facts, book)
        both = heath_side & lean_side
        lean_only = lean_side - heath_side
        heath_only = sorted(heath_side - lean_side, key=edge_order)
        # The counts printed below tie the two graphs together; they must add up.
        assert len(both) + len(lean_only) == len(lean_side)
        assert len(both) + len(heath_only) == len(heath_side)
        out += [f"## Book {book}", "", f"### {GRAPH_SECTIONS[0]}", "",
                f"{arrows(len(heath_side))}.", ""]
        out += mermaid(book, count, facts, heath_side) + [""]
        out += [f"### {GRAPH_SECTIONS[1]}", ""]
        if not any(facts.get(f"{book}.{n}") for n in range(1, count + 1)):
            out += ["_The certificate has no entries for this book yet._", ""]
        else:
            own = {e for e in lean_side if e[0].split(".")[0] == book}
            earlier = lean_side - own
            if book == next(iter(BOOKS)) or not earlier:
                out += [f"{arrows(len(lean_side))}: {len(both)} also among Heath's "
                        f"references (solid) and {len(lean_only)} only in the Lean (dashed).",
                        ""]
                out += mermaid(book, count, facts, lean_side, dashed=lean_only) + [""]
            else:
                # An earlier book's propositions, drawn as nodes, would crowd the graph
                # into a strip: they go in a table under it instead.
                own_both = own & heath_side
                out += [f"{arrows(len(lean_side))}: {len(both)} also among Heath's references "
                        f"and {len(lean_only)} only in the Lean. The graph draws the "
                        f"{arrows(len(own))} between propositions of Book {book}, "
                        f"{len(own_both)} solid and {len(own) - len(own_both)} dashed; the "
                        f"table under it lists the other {len(earlier)}, to propositions of "
                        "earlier books.", ""]
                out += mermaid(book, count, facts, own, dashed=lean_only) + [""]
                out += earlier_table(book, count, earlier, heath_side) + [""]
            if heath_only:
                missing = "; ".join(f"{page_link(c)} in {page_link(d)}" for c, d in heath_only)
                out += [f"Heath's references that the Lean does not cite, {len(heath_only)} "
                        f"of his {len(heath_side)}: {missing}.", ""]
            else:
                out += [f"The Lean cites all {len(heath_side)} of Heath's references.", ""]
        out += [f"<details><summary>The {count} propositions of Book {book}</summary>", ""]
        out += [f"- {page_link(f'{book}.{n}')}: {titles[n]}" for n in range(1, count + 1)]
        out += ["", "</details>", ""]
    return "\n".join(out)


# book/names.md: Euclid's numbers beside the Lean's names, for a reader who uses the
# library (README, "Use it") and knows the proposition but not its name.
NAMES_KEY = (("proved", "proved"),
             ("proved-pending", "proved, citing propositions still to be proved"),
             ("sketched", "stated, the proof still a `sorry`"))


def names_page(facts, records):
    """book/names.md: every proposition, porism and companion, book by book, with its
    Lean name, the module to import, its page and its certificate (the table "What it
    rests on" on its page, where a porism or companion has a column of its own).

    The names are facts.json's; a proposition not yet in it is named as FORMALIZATION,
    section 2, names it. The module is the proposition's file, which declares its porism
    and companions too: a name that file does not declare gets no module, so the table
    never sends a reader to import a module that lacks it."""
    used = set()
    sections = []
    for book, (count, titles) in BOOKS.items():
        rows = ["| | Euclid | Lean name | Import | Statement | Certificate |",
                "|---|---|---|---|---|---|"]
        for n in range(1, count + 1):
            ref = f"{book}.{n}"
            p = facts.get(ref)
            record = records.get(ref)
            page = f"{book}/{n:02d}.md"
            path = optional_path(heath.lean_path(book, n))
            here = (set(DECLARATION.findall(check_fidelity.without_comments(read_text(path))))
                    if path is not None else set())
            module_path = path or heath.lean_path(book, n)
            module = (f"[`Elements.Book{book}.Prop{n:02d}`]"
                      f"(../{module_path.relative_to(ROOT).as_posix()})")
            rests = f"[what it rests on]({page}#what-it-rests-on)"
            scope = SCOPE_WORD[record["statement"]["scope"]] if record else ""
            entries = [(p or {"name": f"Book{book}.Prop{n}", "status": "sketched"},
                        f"[{ref}]({page}) {titles[n]}", scope)]
            for a in attached_entries(p, facts):
                r = heath.parse_ref(a["ref"])
                anchor = "porism" if r.kind == "porism" else r.name
                entries.append((a, f"&emsp;[{r}]({page}#{anchor})", ""))
            for e, euclid, word in entries:
                used.add(e["status"])
                local = e["name"].split(".", 1)[1]
                rows.append(f"| {STATUS_SHORT[e['status']]} | {euclid} | "
                            f"`Elements.{e['name']}` | {module if local in here else ''} | "
                            f"{word} | {rests} |")
        sections += [f"## Book {book}", "",
                     f"[The book]({book}/index.md) · "
                     f"[its certificate](../CERTIFICATE.md#book-{book.lower()})", ""]
        sections += rows + [""]
    books = list(BOOKS)
    which = f"Book {books[0]}" if len(books) == 1 else f"Books {books[0]} to {books[-1]}"
    legend = " · ".join(f"{STATUS_SHORT[s]} {t}" for s, t in NAMES_KEY if s in used)
    fronts = and_list(f"[Book {b}]({b}/front.md)" for b in books)
    out = [GENERATED, "# Lean names", "",
           f"Every proposition, porism and companion of {which}, by Euclid's number: its "
           "Lean name, the module that declares it, its page and its certificate. The "
           "table is generated from the Lean and describes the revision it is part of, so "
           "a name added since the release you depend on is not in that release.", "",
           "`import Elements.BookI.Prop20` brings in I.20 with everything it rests on, and "
           "`import Elements` the whole edition. The [README](../README.md) introduces the "
           "library, and [FORMALIZATION](../docs/FORMALIZATION.md), section 2, describes "
           "its statements. "
           "The definitions, postulates and common notions, with their Lean, are on each "
           f"book's front page: {fronts}.", "",
           f"Key to the tables: {legend}. The Lean statement is *whole*, as Euclid states "
           "it; *restricted*, with hypotheses that leave out cases his words admit; or *in "
           "part*, leaving a clause to his words. A porism or a companion stands under its "
           "proposition, in the same module.", ""]
    return "\n".join(out + sections)


def main() -> None:
    count, faults = use_self_check()
    if faults:
        raise SystemExit(f"{len(faults)} fault(s) in render.py's reading of how a declaration "
                         "is used, of a record's order of companions, or of what a carried "
                         "passage is proved as; nothing was rendered:\n"
                         + "\n".join("  ✗ " + f for f in faults))
    print(f"self-check: the listing, the sentence on reading it and the Proof row read "
          f"{count} cases rightly")
    count, faults = modern_figure_self_check()
    if faults:
        raise SystemExit(f"{len(faults)} fault(s) in the modern figure's placement; "
                         "nothing was rendered:\n" + "\n".join("  ✗ " + f for f in faults))
    print(f"self-check: the modern figure is placed or refused rightly in {count} cases")
    entries = decision_entries()
    print(f"decision entries: {len(entries)} checked in docs/decisions/")
    changes, errors = generated_counts.updates(ROOT)
    if errors:
        raise SystemExit("count markers: nothing was rendered:\n" + "\n".join(errors))
    facts = load_facts()
    docs = load_axiom_docs()
    records = load_records()
    for path, text in changes.items():
        write_text(path, text)
    for book, (count, titles) in BOOKS.items():
        out_dir = generated_counts.repository_path(ROOT, ROOT / "book" / book)
        out_dir.mkdir(parents=True, exist_ok=True)
        for n in range(1, count + 1):
            write_text(out_dir / f"{n:02d}.md", page(book, n, count, titles, facts, docs,
                                                  records))
        write_text(out_dir / "index.md", index(book, count, titles, facts, records))
        write_text(out_dir / "front.md", front(book))
    write_text(ROOT / "book" / "names.md", names_page(facts, records))
    write_text(ROOT / "CERTIFICATE.md", certificate(facts, docs, records))
    write_text(ROOT / "GRAPH.md", graph(facts))
    path = ROOT / "README.md"
    text = read_text(path)
    filled = readme(text, facts, records)
    if filled != text:
        write_text(path, filled)
    text = read_text(PROGRAM)
    filled = program_page(text, facts, records, load_program())
    if filled != text:
        write_text(PROGRAM, filled)
    print("rendered book pages, the table of names, CERTIFICATE.md, GRAPH.md, README.md's "
          "scope summaries and PROGRAM.md's status table")


if __name__ == "__main__":
    main()
